// Покровский собор на Рву (1555–1561). Каркас по снимку с Красной площади: оси столпов, радиусы
// барабанов и глав и их высоты сняты со снимка в пикселях; глубина каждого столпа — по плану собора
// (центральный шатровый храм, четыре больших столпа по сторонам и четыре малых по диагоналям
// на общем подклете), перспектива снимка пересчитана в метры.
import { Kit } from './kit.js';

export const PHOTO = 'basil';
export const CENTER = [0, 24, 0];
export const PATCH = [0.47, 0.8, 0.025, 0.04];
export const ORBIT = 0.22;
export const GROUND_PATCH = [0.62, 0.975, 0.15, 0.02]; // брусчатка без машин

const D = 120, EYE = 20, PX = 0.047; // расстояние до шатра, высота фотографа, метров в пикселе у шатра
const sc = (z) => (D - z) / D;
const X = (px, z) => (px - 800) * PX * sc(z);
const Y = (py, z) => EYE + ((1350 - py) * PX - EYE) * sc(z);
const L = (len, z) => len * PX * sc(z);

export function build() {
  const k = new Kit();
  const G = Y(1115, 0), sym = { mirrorZ: 0 };
  // подклет с галереей и кровлей
  k.box(46, G, 36, X(850, 0), 0, 0, sym);
  k.box(44, 1.2, 34, X(850, 0), G, 0, { kind: 'roof', ...sym });
  // центральный храм: восьмерик, шатёр, барабан и золотая глава
  k.drum(L(130, 0), Y(500, 0) - G, 0, G, 0, {}, 8);
  k.tent(L(92, 0), L(40, 0), Y(300, 0) - Y(500, 0), 0, Y(500, 0), 0);
  k.drum(L(30, 0), Y(225, 0) - Y(300, 0), 0, Y(300, 0), 0, {}, 8);
  k.dome(L(47, 0), Y(150, 0) - Y(225, 0), 0, Y(225, 0), 0, 'onion', { kind: 'gold' });
  k.cross(Y(40, 0) - Y(150, 0), 0, Y(150, 0), 0);
  // столпы: ось на снимке, глубина, r барабана, r главы, низ и верх главы, верх креста (px)
  const pillars = [
    [862, 12, 120, 136, 720, 480, 330],   // передний большой, глава с зигзагом
    [487, -1, 72, 92, 790, 600, 495],     // левый большой
    [1230, 3, 70, 116, 810, 590, 460],    // правый большой, витая зелёная глава
    [618, 9, 65, 96, 900, 720, 640],      // малый слева, жёлтая глава
    [1110, 9, 52, 77, 900, 775, 690],     // малый справа, полосатая глава
    [1040, -9, 45, 50, 1000, 900, 840],   // малый за правым
    [600, -9, 45, 50, 1000, 900, 840],    // малый за левым (на снимке закрыт)
    [800, -13, 70, 92, 790, 600, 495],    // задний большой (закрыт шатром)
  ];
  for (const [px, z, dr, gr, gb, gt, ct] of pillars) {
    const x = X(px, z), b = Y(gb, z);
    k.drum(L(dr, z), b - G - 2, x, G, z, {}, 8);
    k.drum(L(dr, z) * 0.8, 2, x, b - 2, z, {}, 16);
    k.dome(L(gr, z), Y(gt, z) - b, x, b, z, 'onion');
    k.drum(0.45, Y(ct, z) - Y(gt, z) - 2.4, x, Y(gt, z), z);
    k.cross(2.4, x, Y(ct, z) - 2.4, z);
  }
  // придел Василия Блаженного с двумя шатриками
  k.box(L(150, 8), Y(1190, 8), 8, X(405, 8), 0, 8, { mirrorZ: 8 });
  for (const px of [405, 435]) k.tent(2, 0.25, Y(1030, 8) - Y(1190, 8), X(px, 8), Y(1190, 8), 8);
  // колокольня поодаль: четверик, восьмерик со звонницей, шатёр и глава
  const bz = -20, bx = X(1575, bz);
  k.box(L(170, bz), Y(1150, bz), L(170, bz), bx, 0, bz, { mirrorZ: bz });
  k.drum(L(80, bz), Y(1000, bz) - Y(1150, bz), bx, Y(1150, bz), bz, {}, 8);
  k.tent(L(75, bz), L(18, bz), Y(650, bz) - Y(1000, bz), bx, Y(1000, bz), bz);
  k.dome(L(22, bz), Y(600, bz) - Y(650, bz), bx, Y(650, bz), bz, 'onion');
  k.cross(2, bx, Y(600, bz), bz);
  return k.group;
}

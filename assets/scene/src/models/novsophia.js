// Софийский собор Великого Новгорода (1045–1050). Каркас по западному фасаду со снимка:
// размеры сняты с фотографии (1 px ≈ 3 см), глубина — по плану собора.
import { Kit } from './kit.js';

export const PHOTO = 'novsophia';
export const CENTER = [3, 12, -13]; // центр, вокруг которого облетает камера
// Участок гладкой побелки на снимке (доли ширины/высоты): им покрываются стены, которых не видно на фото
export const PATCH = [0.25, 0.6, 0.07, 0.15];
export function build() {
  const k = new Kit();
  const back = -26, mid = -13;
  const wall = { mirrorZ: mid };
  k.box(32.7, 14.1, 26, 0, 0, -13, wall);                // основной объём с галереями
  k.box(3.2, 5.9, 20, 17.9, 0, -13, wall);               // низкая пристройка справа
  k.box(15, 4.8, 22, 0.6, 14.1, -13, wall);              // верхний ярус над галереями
  k.zakomaras(-6.9, 8.1, 3, 18.9, 0, 22, wall);          // закомары верхнего яруса
  k.box(32.7, 1.4, 26, 0, 14.1, -13, { kind: 'roof', mirrorZ: mid }); // кровли галерей
  // лестничная башня с главой
  k.drum(4.35, 3.2, -11, 14.1, -4.6);
  k.drum(4.35, 3.5, -11, 17.3, -4.6);
  k.dome(4.3, 7.5, -11, 20.7, -4.6, 'onion');
  k.cross(2.2, -11, 28.1, -4.6);
  // пять глав над храмом: центральная золотая и четыре угловые
  const heads = [[-1.6, -7, 2.7, 17.85, 4.05, 2.85, 5.55], [9, -7, 2.8, 17.85, 4.35, 2.85, 5.55], [-1.6, -19, 2.7, 17.85, 4.05, 2.85, 5.55], [9, -19, 2.8, 17.85, 4.35, 2.85, 5.55]];
  for (const [x, z, r, y, h, dr, dh] of heads) { k.drum(r, h, x, y, z); k.dome(dr, dh, x, y + h, z, 'onion'); k.cross(1.6, x, y + h + dh, z); }
  k.drum(2.8, 5.4, 3.15, 19.2, -13);
  k.dome(3.55, 6, 3.15, 24.6, -13, 'helmet', { kind: 'gold' });
  k.cross(2, 3.15, 30.6, -13);
  return k.group;
}

// Большой Петергофский дворец (1714–1755). Каркас по снимку из Нижнего парка у Большого каскада:
// длинный корпус на террасе над каскадом, ризалит с фронтоном по оси, высокие вальмовые кровли,
// над серединой — золочёная корона. Склон с лестницами и каскад — со снимка.
import { Kit } from './kit.js';

export const PHOTO = 'peterhof';
export const TER = 20; // терраса дворца над Нижним парком
const SLOPE = 45; // заложение склона до Нижнего парка
export const CENTER = [0, TER + 10, -12];
export const PATCH = [0.45, 0.385, 0.02, 0.03];
export const ORBIT = 0.12; // на переднем плане люди и фонтаны — облёт небольшой, больше наезд
export const GROUND_PATCH = [0.55, 0.83, 0.15, 0.03]; // газон Нижнего парка
export function build() {
  const k = new Kit();
  const sym = { mirrorZ: -12 };
  k.box(300, TER, 30, 2.5, 0, -15, { mirrorZ: null });     // терраса
  k.slope(300, TER, SLOPE, 2.5, 0, 0);                      // склон с Большим каскадом и лестницами
  k.box(155, 17, 24, 2.5, TER, -12, sym);                   // корпус
  k.box(30, 17, 2.5, 0, TER, 1.25, { mirrorZ: null });     // центральный ризалит
  k.gable(26, 4.5, 2.5, 0, TER + 17, 2.5);                  // фронтон
  k.hip(155, 24, 7, 7, 2.5, TER + 17, -12, sym);            // кровля корпуса
  k.hip(32, 26, 10, 8, 0, TER + 17, -12, sym);              // высокая кровля над серединой
  k.drum(1.4, 2.4, 0, TER + 27, -12, { kind: 'gold' }, 12); // корона
  k.dome(1.6, 2.2, 0, TER + 29.4, -12, 'helmet', { kind: 'gold' });
  return k.group;
}
